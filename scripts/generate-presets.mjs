#!/usr/bin/env node
// Converts device-specs/*.json (Flutter device_preview format) into TypeScript
// presets under packages/react-native-device-simulator/src/presets/generated.
// Run: node scripts/generate-presets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const specsDir = path.join(root, 'device-specs');
const outDir = path.join(root, 'packages/react-native-device-simulator/src/presets/generated');

const PLATFORMS = { ios: 'ios', android: 'android', macos: 'macos', windows: 'windows', linux: 'linux', fuchsia: 'android' };
const join = (v) => (Array.isArray(v) ? v.join('\n') : v);
const insets = (v) => (v ? { top: v.top ?? 0, right: v.right ?? 0, bottom: v.bottom ?? 0, left: v.left ?? 0 } : undefined);

/** "iPhone 17 Pro" -> iPhone17Pro, "Galaxy Z Fold8" -> galaxyZFold8, 'iPad Air 11" (M2)' -> iPadAir11M2 */
function exportName(name) {
  const words = name.replace(/["()+]/g, (c) => (c === '+' ? ' Plus' : ' ')).split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = words.map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join('');
  return /^i[A-Z]/.test(joined) ? joined : joined[0].toLowerCase() + joined.slice(1);
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const entries = [];
for (const file of fs.readdirSync(specsDir).filter((f) => f.endsWith('.json')).sort()) {
  const spec = JSON.parse(fs.readFileSync(path.join(specsDir, file), 'utf8'));
  const platform = PLATFORMS[String(spec.platform).toLowerCase()];
  if (!platform) throw new Error(`${file}: unknown platform ${spec.platform}`);
  const preset = {
    id: spec.id,
    name: spec.name,
    brand: spec.brand,
    year: spec.year,
    platform,
    kind: spec.kind ?? 'phone',
    portraitSize: spec.portraitSize,
    devicePixelRatio: spec.devicePixelRatio,
    portraitPadding: insets(spec.portraitPadding) ?? { top: 0, right: 0, bottom: 0, left: 0 },
    landscapePadding: insets(spec.landscapePadding),
    portraitKeyboardHeight: spec.portraitKeyboardHeight,
    landscapeKeyboardHeight: spec.landscapeKeyboardHeight,
    displayFeatures: spec.displayFeatures?.map((f) => ({
      bounds: f.bounds,
      type: f.type ?? 'unknown',
      state: { postureFlat: 'flat', postureHalfOpened: 'halfOpened' }[f.state] ?? f.state ?? 'unknown',
    })),
    frame: spec.frame && {
      size: spec.frame.size,
      screenOffset: spec.frame.screenOffset,
      screenPath: spec.frame.screenPath,
      body: join(spec.frame.body),
    },
    systemUi: spec.systemUi && {
      statusBar: spec.systemUi.statusBar && {
        inset: spec.systemUi.statusBar.inset,
        leading: join(spec.systemUi.statusBar.leading),
        trailing: join(spec.systemUi.statusBar.trailing),
        center: join(spec.systemUi.statusBar.center),
      },
      navigationBar: spec.systemUi.navigationBar && {
        leading: join(spec.systemUi.navigationBar.leading),
        center: join(spec.systemUi.navigationBar.center),
        trailing: join(spec.systemUi.navigationBar.trailing),
        bottomInset: spec.systemUi.navigationBar.bottomInset,
      },
    },
  };
  const name = exportName(spec.name);
  const fileBase = spec.id;
  fs.writeFileSync(
    path.join(outDir, `${fileBase}.ts`),
    `// Generated by scripts/generate-presets.mjs from device-specs/${file}. Do not edit.\n` +
      `// Device artwork: MIT, (c) Aloïs Deniel - see device-specs/LICENSE.\n` +
      `import type { DevicePreset } from '../../types';\n\n` +
      `export const ${name}: DevicePreset = ${JSON.stringify(preset, null, 2)};\n`,
  );
  entries.push({ name, fileBase, brand: spec.brand ?? '', year: spec.year ?? 0 });
}

entries.sort((a, b) => a.brand.localeCompare(b.brand) || b.year - a.year || a.name.localeCompare(b.name));
fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  `// Generated by scripts/generate-presets.mjs. Do not edit.\n` +
    entries.map((e) => `import { ${e.name} } from './${e.fileBase}';`).join('\n') +
    `\n\nexport { ${entries.map((e) => e.name).join(', ')} };\n\n` +
    `/** Every built-in device, grouped by brand, newest first. */\n` +
    `export const generatedPresets = [${entries.map((e) => e.name).join(', ')}];\n`,
);
console.log(`Generated ${entries.length} presets:`, entries.map((e) => e.name).join(', '));
